/**
 * z-index 레이어 스케일 — 겹치는 오버레이들의 단일 출처.
 *
 * 왜 필요한가:
 *   각 컴포넌트가 제각기 z 값을 박아두면(z-50 / z-[60] / z-[300] …) 어떤 오버레이가
 *   위인지 아무도 모른다. 실제로 스케줄 편집 모달(z-[300]) 안에서 띄운 confirm
 *   (공용 Modal, z-50)이 편집 모달 뒤로 깔려서, 사용자는 확인창을 못 보고 백드롭만
 *   겹겹이 쌓여 화면이 까맣게 변하는 사고가 났다.
 *
 * 규칙:
 *   - 새 오버레이는 반드시 이 표의 값을 쓴다. 임의 숫자 금지.
 *   - 순서 뒤집을 일 있으면 이 파일에서 바꾼다.
 *
 * 순서(아래로 갈수록 위):
 *   DROPDOWN  드롭다운/팝오버/컨텍스트 메뉴 — 페이지 콘텐츠 위
 *   PANEL     사이드 드로어/히스토리 패널
 *   MODAL     일반 모달 (폼·상세 등 화면 단위 대화상자)
 *   LIGHTBOX  전체화면 이미지 뷰어 — 모달 본문에서 열리므로 모달보다 위
 *   DIALOG    confirm/alert 셸 — 어떤 오버레이 위에서도 응답 가능해야 하므로 최상단
 *   TOAST     자동 소멸 알림 — 무엇도 가리지 않도록 맨 위
 */
export const LAYER = {
  DROPDOWN: "z-[100]",
  PANEL: "z-[200]",
  MODAL: "z-[300]",
  LIGHTBOX: "z-[400]",
  DIALOG: "z-[500]",
  TOAST: "z-[600]",
} as const;

export type LayerName = keyof typeof LAYER;
